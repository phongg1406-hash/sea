from playwright.sync_api import sync_playwright
from pathlib import Path
out=Path(__file__).parent
root=out.parent
html=(root/'index.html').read_text(encoding='utf8')
css=(root/'styles.css').read_text(encoding='utf8')
js=(root/'app.js').read_text(encoding='utf8')
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage','--no-proxy-server'])
    errors=[]
    def load(page):
        page.on('pageerror',lambda exc:errors.append(str(exc)))
        # The restricted test browser blocks navigation to file:/localhost. Inject local sources instead.
        page.set_content(html,wait_until='domcontentloaded')
        page.add_style_tag(content=css)
        page.add_script_tag(content=js)
        page.wait_for_timeout(400)
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    load(page)
    page.screenshot(path=str(out/'desktop-home.png'))
    print('desktop',page.title(),'scene',page.locator('#scene-label').inner_text())
    page.locator('.site-nav [data-goto="selected-work"]').click()
    page.wait_for_timeout(850)
    page.screenshot(path=str(out/'desktop-work.png'))
    print('scene after work',page.locator('#scene-label').inner_text())
    page.locator('.site-nav [data-goto="playground"]').click()
    page.wait_for_timeout(850)
    page.screenshot(path=str(out/'desktop-playground.png'))
    print('playground scene',page.locator('#scene-label').inner_text())
    page.locator('.site-nav [data-goto="selected-work"]').click()
    page.wait_for_timeout(850)
    page.locator('[data-project="light"]').first.click(force=True)
    print('dialog',page.locator('#project-dialog').evaluate('(x)=>x.open'))
    page.locator('#close-dialog').click()
    page.locator('#home-view').click()
    page.wait_for_timeout(750)
    box=page.locator('#viewport').bounding_box()
    for i in range(20):
        page.mouse.move(box['x']+120+i*15,box['y']+450+(i%6)*5)
        page.wait_for_timeout(15)
    print('waterWakeCount',page.evaluate('window.__sunlitDebug.getWakeCount()'))
    page.get_by_role('button',name='Motion: on').click()
    print('motion toggled',page.locator('#motion-toggle').inner_text())
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,is_mobile=True,has_touch=True)
    load(mobile)
    mobile.screenshot(path=str(out/'mobile-home.png'))
    print('mobile horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth>window.innerWidth'))
    mobile.locator('.menu-toggle').click()
    print('mobile menu links',mobile.locator('.mobile-menu a:visible').count())
    mobile.locator('.mobile-menu [data-goto="selected-work"]').click()
    mobile.wait_for_timeout(700)
    mobile.screenshot(path=str(out/'mobile-work.png'))
    print('mobile scrollTop',mobile.evaluate('window.scrollY'))
    mobile.locator('[data-project="light"]').first.click(force=True)
    print('mobile dialog',mobile.locator('#project-dialog').evaluate('(x)=>x.open'))
    mobile.locator('#close-dialog').click()
    print('errors',errors)
    browser.close()
